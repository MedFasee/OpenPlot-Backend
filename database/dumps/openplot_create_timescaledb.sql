-- OpenPlot - schema ajustado para TimescaleDB
-- Script DDL limpo: cria schema, tipos, tabelas, constraints, indices, hypertable e grants.
-- Nao inclui dados, COPY, DROP nem CREATE DATABASE.
-- Recomendado executar em um banco ja criado, por exemplo: database openplot, schema openplot.
-- Requisito: a extensao TimescaleDB deve estar disponivel no servidor PostgreSQL.

SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;

-- -----------------------------------------------------------------------------
-- TimescaleDB
-- -----------------------------------------------------------------------------
-- Em Docker, utilize uma imagem com TimescaleDB instalado, por exemplo timescale/timescaledb.
-- Este comando precisa ser executado por usuario com permissao para criar extensoes.

CREATE EXTENSION IF NOT EXISTS timescaledb;

-- -----------------------------------------------------------------------------
-- Schema e role de leitura
-- -----------------------------------------------------------------------------

CREATE SCHEMA IF NOT EXISTS openplot;
SET search_path = openplot, public;

-- Role opcional para Grafana.
-- Por seguranca, a role e criada sem LOGIN. Caso o Grafana conecte diretamente,
-- defina LOGIN e PASSWORD em um script separado/seguro.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_catalog.pg_roles
        WHERE rolname = 'grafana'
    ) THEN
        CREATE ROLE grafana;
    END IF;
END
$$;

GRANT USAGE ON SCHEMA openplot TO grafana;

DO $$
BEGIN
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO grafana', current_database());
END
$$;

-- -----------------------------------------------------------------------------
-- Tipos controlados
-- -----------------------------------------------------------------------------
-- Observacao: mantidos os valores ja usados pelo projeto para reduzir impacto
-- na API/front. THD foi adicionado em qty_kind por aparecer como grandeza
-- analitica em agrupamentos anteriores.

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE n.nspname = 'openplot'
          AND t.typname = 'qty_kind'
    ) THEN
        CREATE TYPE openplot.qty_kind AS ENUM (
            'Voltage',
            'Current',
            'Frequency',
            'Digital',
            'THD'
        );
    END IF;
END
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE n.nspname = 'openplot'
          AND t.typname = 'phase_kind'
    ) THEN
        CREATE TYPE openplot.phase_kind AS ENUM (
            'A',
            'B',
            'C',
            'None',
            'Digital'
        );
    END IF;
END
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE n.nspname = 'openplot'
          AND t.typname = 'comp_kind'
    ) THEN
        CREATE TYPE openplot.comp_kind AS ENUM (
            'MAG',
            'ANG',
            'FREQ',
            'DFREQ',
            'THD',
            'DIG'
        );
    END IF;
END
$$;

