CREATE TABLE IF NOT EXISTS openplot.pdc (
    pdc_id      integer GENERATED BY DEFAULT AS IDENTITY,
    name        text NOT NULL,
    kind        text NOT NULL,
    fps         integer NOT NULL,
    address     text NOT NULL,
    username    text,
    password    text,
    db_name     text,
    active      boolean NOT NULL DEFAULT true,

    CONSTRAINT pdc_pkey PRIMARY KEY (pdc_id),
    CONSTRAINT pdc_name_key UNIQUE (name),
    CONSTRAINT pdc_fps_check CHECK (fps > 0)
);

CREATE TABLE IF NOT EXISTS openplot.pmu (
    pmu_id      integer GENERATED BY DEFAULT AS IDENTITY,
    id_name     text NOT NULL,
    full_name   text,
    volt_level  integer,
    area        text,
    state       text,
    station     text,
    lat         double precision,
    lon         double precision,

    CONSTRAINT pmu_pkey PRIMARY KEY (pmu_id),
    CONSTRAINT pmu_id_name_key UNIQUE (id_name),
    CONSTRAINT pmu_lat_check CHECK (lat IS NULL OR (lat >= -90 AND lat <= 90)),
    CONSTRAINT pmu_lon_check CHECK (lon IS NULL OR (lon >= -180 AND lon <= 180))
);

CREATE TABLE IF NOT EXISTS openplot.pdc_pmu (
    pdc_pmu_id       integer GENERATED BY DEFAULT AS IDENTITY,
    pdc_id           integer NOT NULL,
    pmu_id           integer NOT NULL,
    pdc_local_id     text,
    kind             text,
    local_numeric_id integer,

    CONSTRAINT pdc_pmu_pkey PRIMARY KEY (pdc_pmu_id),
    CONSTRAINT pdc_pmu_pdc_id_pmu_id_key UNIQUE (pdc_id, pmu_id),
    CONSTRAINT pdc_pmu_pdc_id_fkey
        FOREIGN KEY (pdc_id)
        REFERENCES openplot.pdc (pdc_id)
        ON DELETE CASCADE,
    CONSTRAINT pdc_pmu_pmu_id_fkey
        FOREIGN KEY (pmu_id)
        REFERENCES openplot.pmu (pmu_id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS openplot.signal (
    signal_id       integer GENERATED BY DEFAULT AS IDENTITY,
    pdc_pmu_id      integer NOT NULL,
    name            text NOT NULL,
    historian_point integer NOT NULL,
    quantity        openplot.qty_kind NOT NULL,
    phase           openplot.phase_kind NOT NULL DEFAULT 'None',
    component       openplot.comp_kind NOT NULL,

    CONSTRAINT signal_pkey PRIMARY KEY (signal_id),
    CONSTRAINT signal_pdc_pmu_id_fkey
        FOREIGN KEY (pdc_pmu_id)
        REFERENCES openplot.pdc_pmu (pdc_pmu_id)
        ON DELETE CASCADE,

    -- Necessaria para uso seguro de ON CONFLICT na importacao de XML/sinais.
    CONSTRAINT signal_pdc_pmu_name_phase_component_key
        UNIQUE (pdc_pmu_id, name, phase, component),

    -- Evita combinacoes sem sentido para digitais, mas ainda permite phase='Digital'
    -- por compatibilidade com dados/codigo existentes.
    CONSTRAINT signal_digital_consistency_check CHECK (
        (quantity = 'Digital' AND component = 'DIG')
        OR
        (quantity <> 'Digital' AND component <> 'DIG')
    )
);

CREATE TABLE IF NOT EXISTS openplot.signal_points (
    signal_id integer NOT NULL,
    pdc_id    integer NOT NULL,
    role      text NOT NULL,
    point_id  bigint NOT NULL,

    CONSTRAINT signal_points_pkey PRIMARY KEY (signal_id, role),
    CONSTRAINT signal_points_pdc_id_point_id_key UNIQUE (pdc_id, point_id),
    CONSTRAINT signal_points_signal_id_fkey
        FOREIGN KEY (signal_id)
        REFERENCES openplot.signal (signal_id)
        ON DELETE CASCADE,
    CONSTRAINT signal_points_pdc_id_fkey
        FOREIGN KEY (pdc_id)
        REFERENCES openplot.pdc (pdc_id)
        ON DELETE CASCADE
);

