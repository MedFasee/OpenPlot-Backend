CREATE TABLE IF NOT EXISTS openplot.search_runs (
    id           uuid NOT NULL,
    source       text NOT NULL,
    terminal_id  text,
    signals      jsonb NOT NULL,
    from_ts      timestamp with time zone NOT NULL,
    to_ts        timestamp with time zone NOT NULL,
    select_rate  integer NOT NULL DEFAULT 0,
    status       text NOT NULL,
    progress     integer NOT NULL DEFAULT 0,
    message      text,
    created_at   timestamp with time zone NOT NULL DEFAULT now(),
    pdc_id       integer,
    signal_count integer DEFAULT 0,
    pmu_count    integer DEFAULT 0,
    label        text,
    pmus         jsonb,
    pmus_ok      jsonb,
    username     text,
    shared       boolean NOT NULL DEFAULT false,
    is_visible   boolean NOT NULL DEFAULT true,
    deleted_at   timestamp with time zone,
    started_at   timestamp with time zone,
    finished_at  timestamp with time zone,

    CONSTRAINT search_runs_pkey PRIMARY KEY (id),
    CONSTRAINT search_runs_pdc_id_fkey
        FOREIGN KEY (pdc_id)
        REFERENCES openplot.pdc (pdc_id)
        ON DELETE SET NULL,
    CONSTRAINT search_runs_status_check CHECK (
        status IN ('queued', 'running', 'done', 'failed', 'canceled')
    ),
    CONSTRAINT search_runs_progress_check CHECK (progress >= 0 AND progress <= 100),
    CONSTRAINT search_runs_select_rate_check CHECK (select_rate >= 0),
    CONSTRAINT search_runs_signal_count_check CHECK (signal_count IS NULL OR signal_count >= 0),
    CONSTRAINT search_runs_pmu_count_check CHECK (pmu_count IS NULL OR pmu_count >= 0),
    CONSTRAINT search_runs_time_range_check CHECK (from_ts <= to_ts),
    CONSTRAINT search_runs_finished_after_started_check CHECK (
        started_at IS NULL
        OR finished_at IS NULL
        OR started_at <= finished_at
    )
);

CREATE TABLE IF NOT EXISTS openplot.analysis_cache (
    cache_id         uuid NOT NULL,
    job_id           uuid NOT NULL,
    payload          jsonb NOT NULL,
    last_accessed_at timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT analysis_cache_pkey PRIMARY KEY (cache_id),
    CONSTRAINT analysis_cache_job_id_fkey
        FOREIGN KEY (job_id)
        REFERENCES openplot.search_runs (id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS openplot.ingest_chunks (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    job_id      uuid NOT NULL,
    signal_id   integer NOT NULL,
    from_ts     timestamp with time zone NOT NULL,
    to_ts       timestamp with time zone NOT NULL,
    rowcount    integer NOT NULL,
    inserted_at timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT ingest_chunks_pkey PRIMARY KEY (id),
    CONSTRAINT ingest_chunks_job_id_fkey
        FOREIGN KEY (job_id)
        REFERENCES openplot.search_runs (id)
        ON DELETE CASCADE,
    CONSTRAINT ingest_chunks_signal_id_fkey
        FOREIGN KEY (signal_id)
        REFERENCES openplot.signal (signal_id)
        ON DELETE CASCADE,
    CONSTRAINT ingest_chunks_time_range_check CHECK (from_ts <= to_ts),
    CONSTRAINT ingest_chunks_rowcount_check CHECK (rowcount >= 0)
