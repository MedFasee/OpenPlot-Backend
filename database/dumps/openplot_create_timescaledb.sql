-- -----------------------------------------------------------------------------
-- Funcao de limpeza do cache
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION openplot.clean_expired_analysis_cache()
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    DELETE FROM openplot.analysis_cache
    WHERE last_accessed_at < now() - INTERVAL '24 hours';
END;
$$;

